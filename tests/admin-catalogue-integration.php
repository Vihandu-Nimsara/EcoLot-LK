<?php
declare(strict_types=1);
require_once __DIR__ . '/support/bootstrap.php';
$db = Database::connection();
$original = (string)$db->query('SELECT DATABASE()')->fetchColumn();
$name = 'ecolot_catalogue_test_' . bin2hex(random_bytes(6));
$db->exec("CREATE DATABASE `$name` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
$count=0;
$check=static function(bool $ok,string $message)use(&$count):void{verify($ok,$message);$count++;};
$reject=static function(callable $fn)use($check):void{try{$fn();}catch(DomainException){$check(true,'Expected rejection');return;}throw new RuntimeException('Expected rejection missing');};
try {
    $db->exec("USE `$name`");
    verify($db->query('SELECT DATABASE()')->fetchColumn()===$name,'Wrong database');
    TestDatabase::loadSchema($db);
    $month = TestDatabase::seedScheduleActors($db);
    $db->exec("INSERT INTO users(user_id,full_name,mobile_number,password_hash,role,account_status) VALUES (4,'Admin','0771111111','unused','ADMIN','ACTIVE'),(5,'Suspended admin','0771111112','unused','ADMIN','SUSPENDED')");
    $db->exec('INSERT INTO administrators VALUES (4),(5)');
    $db->exec("INSERT INTO waste_categories(category_id,category_name,category_status) VALUES (1,'Domestic E-Waste','ACTIVE'),(2,'Office E-Waste','ACTIVE'),(3,'Industrial E-Waste','INACTIVE'),(4,'Medical E-Waste','ACTIVE'),(5,'Automobile E-Waste','ACTIVE'),(6,'E-Waste We Do Not Collect','ACTIVE'),(7,'Nonstandard fixture','ACTIVE')");
    $svc=new AdminCatalogueService($db); $model=new EWasteItem($db);
    $categoriesBefore=$db->query('SELECT * FROM waste_categories ORDER BY category_id')->fetchAll();
    $i=['category_id'=>'1','item_name'=>'New device','collection_status'=>'ACCEPTED','default_risk_level'=>'LOW','item_status'=>'INACTIVE'];
    $reject(fn()=>$svc->saveItem(2,null,$i));
    $reject(fn()=>$svc->saveItem(5,null,$i));
    $reject(fn()=>$svc->saveItem(4,null,array_replace($i,['category_id'=>'3'])));
    $reject(fn()=>$svc->saveItem(4,null,array_replace($i,['category_id'=>'7'])));
    $reject(fn()=>$svc->saveItem(4,null,array_replace($i,['category_id'=>'6'])));
    $iid=$svc->saveItem(4,null,$i);
    $check(count($model->pickupCatalogue())===0,'Inactive draft hidden');
    $reject(fn()=>$svc->saveItem(4,null,$i));
    $reject(fn()=>$svc->saveItem(4,$iid,array_replace($i,['category_id'=>'2'])));
    $i=array_replace($i,['item_name'=>'Corrected device','item_status'=>'ACTIVE']);
    $svc->saveItem(4,$iid,$i);
    $check(count($model->pickupCatalogue())===1,'Active corrected item visible');
    $raw=[['category'=>'Domestic E-Waste','item'=>'Corrected device','quantity'=>'1','weight'=>'1','condition'=>'WORKING','note'=>'']];
    $svc->saveItem(4,$iid,array_replace($i,['collection_status'=>'REVIEW_REQUIRED','default_risk_level'=>'HIGH']));
    $validated=$model->validatePickupItems($raw);
    $check($validated[0]['applied_risk_level']==='HIGH' && $validated[0]['requires_review']===true,'Default pickup policy applied');
    $db->prepare("INSERT INTO risk_rules(waste_item_id,condition_type,risk_level,action_note) VALUES (?,'WORKING','MEDIUM','Test')")->execute([$iid]);
    $validated=$model->validatePickupItems($raw);
    $check($validated[0]['applied_risk_level']==='HIGH' && $validated[0]['requires_review']===true,'Active rule cannot lower default risk, review policy remains');
    $reject(fn()=>$svc->saveItem(4,$iid,array_replace($i,['item_name'=>'Different device'])));
    $check((int)$svc->items()[0]['name_locked']===1,'Rule-linked item locked in read model');
    $schedule=(new AreaCollectionSchedule($db))->create(['campaign_id'=>1,'postal_area_id'=>1,'created_by_officer_user_id'=>1,'collection_date'=>"$month-10",'request_cutoff_at'=>"$month-08 23:59:59",'request_capacity'=>2,'schedule_status'=>'OPEN']);
    $requestId=(new EWasteRequest($db))->createWithItems(['public_user_id'=>2,'schedule_id'=>$schedule],$raw);
    $check((new EWasteRequest($db))->find($requestId)['request_status']==='PENDING_REVIEW','Actual request requires review');
    $db->exec('DELETE FROM risk_rules'); // Test fixture only, isolates the historical-request rename guard.
    $reject(fn()=>$svc->saveItem(4,$iid,array_replace($i,['item_name'=>'Different device'])));
    $db->prepare("INSERT INTO risk_rules(waste_item_id,condition_type,risk_level,action_note) VALUES (?,'WORKING','MEDIUM','Test')")->execute([$iid]);
    $svc->saveItem(4,$iid,array_replace($i,['item_status'=>'INACTIVE']));
    $check(count($model->pickupCatalogue())===0,'Inactive item hidden');
    $reject(fn()=>$model->validatePickupItems($raw));
    $check((int)$db->query('SELECT COUNT(*) FROM risk_rules')->fetchColumn()===1,'Risk rule preserved');
    $check((int)$db->query('SELECT COUNT(*) FROM request_items')->fetchColumn()===1,'Historical request item preserved');
    $svc->saveItem(4,$iid,$i);
    $check(count($model->pickupCatalogue())===1,'Reactivation restores item');
    $svc->saveItem(4,$iid,array_replace($i,['collection_status'=>'DO_NOT_COLLECT']));
    $check(count($model->pickupCatalogue())===0,'Excluded item hidden');
    $reject(fn()=>$model->validatePickupItems($raw));
    $excluded=$svc->saveItem(4,null,array_replace($i,['category_id'=>'6','item_name'=>'Excluded fixture','collection_status'=>'DO_NOT_COLLECT']));
    $reject(fn()=>$svc->saveItem(4,$excluded,array_replace($i,['category_id'=>'6','item_name'=>'Excluded fixture'])));
    $check(count($model->pickupCatalogue())===0,'Excluded category item never selectable');
    $check($db->query('SELECT * FROM waste_categories ORDER BY category_id')->fetchAll()===$categoriesBefore,'All categories unchanged');
    $check((int)$db->query("SELECT COUNT(*) FROM audit_logs WHERE action_type LIKE 'CATALOGUE_ITEM_%'")->fetchColumn()===7,'Only successful catalogue changes audited');
    $check(!$db->inTransaction(),'No leaked transaction');
    echo "PASS: $count catalogue integration checks\n";
} finally {
    if ($db->inTransaction()) $db->rollBack();
    $db->exec('USE `' . str_replace('`','``',$original) . '`');
    $db->exec("DROP DATABASE `$name`");
}
